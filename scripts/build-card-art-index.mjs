// Only existing JPG assets may be chosen as profile artwork.
import { readdir, readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const ids = (await readdir(new URL('images/cards/', root)))
  .filter((n) => n.endsWith('.jpg'))
  .map((n) => n.slice(0, -4))
  .sort();
const target = new URL('js/cardArtIds.js', root);
const text = `// Generated by scripts/build-card-art-index.mjs.\nexport const CARD_ART_IDS = new Set(${JSON.stringify(ids, null, 2)});\n`;
// Use semantic comparison so formatting never invalidates the index.
if (process.argv.includes('--check')) {
  const { CARD_ART_IDS } = await import(target.href);
  if (JSON.stringify([...CARD_ART_IDS]) !== JSON.stringify(ids))
    throw Error('Artwork index is stale: run node scripts/build-card-art-index.mjs');
  console.log(`Artwork index verified: ${ids.length} files`);
} else await writeFile(target, text);
